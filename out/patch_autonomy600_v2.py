    s = io.open(P, encoding="utf-8").read()
    if MARK in s:
        print("already patched")
        return 0
    miss = []
    for old, new in A_FIX:
        if old not in s:
            miss.append(old)
            continue
        s = s.replace(old, new, 1)
    if miss:
        print("MISS %d:" % len(miss))
